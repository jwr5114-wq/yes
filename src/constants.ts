export function getKoreanPrefix(index: number): string {
  const koreanInitials = ["가", "나", "다", "라", "마", "바", "사", "아", "자", "차", "카", "타", "파", "하"];
  if (index < koreanInitials.length) {
    return koreanInitials[index];
  }
  return String.fromCharCode(0xac00 + index);
}

